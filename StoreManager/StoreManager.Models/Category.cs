// -----------------------------------------------
// این فایل قالب دسته‌بندی کالاهاست
// مثلاً: لبنیات، نوشیدنی، تنقلات و...
// -----------------------------------------------

namespace StoreManager.Models
{
    // هر دسته‌بندی این اطلاعات رو داره
    public class Category
    {
        // شماره یونیک دسته‌بندی
        public int Id { get; set; }

        // اسم دسته‌بندی - مثلاً "لبنیات" یا "مواد غذایی"
        public string Name { get; set; }

        // آیکون دسته‌بندی - مثلاً "🥛" یا "🍕"
        // میشه ازش برای نمایش توی منو استفاده کرد
        public string Icon { get; set; }

        // اگه این دسته‌بندی زیرمجموعه دسته دیگه‌ایه، اینجا مشخص میشه
        // مثلاً "پنیر" زیرمجموعه "لبنیات"
        // اگه 0 باشه یعنی دسته‌بندی اصلیه (ریشه)
        public int ParentId { get; set; }

        // فعاله یا نه؟
        public bool IsActive { get; set; } = true;
    }
}
